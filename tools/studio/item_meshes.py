#!/usr/bin/env python3
"""Copy the item models imported in Studio into the repo (macOS).

The FBX items (assets/items) are imported by hand into the published place
(ServerStorage, one Model per item, MeshParts with uploaded mesh and texture
ids). This reads them out of that place with `RobloxStudio -task RunScript`
and writes roblox/ServerScriptService/Modules/ItemMeshData.lua: per item, its
parts (mesh id, texture id, size, CFrame relative to the model centre).
ItemModelPreloader builds the models from that file with
AssetService:CreateMeshPartAsync when the place has no imported copy (Rojo
test places, a fresh place), so every place shows the same models.

  python3 tools/studio/item_meshes.py                     # default place
  python3 tools/studio/item_meshes.py --place-id 1 --universe-id 2

Run it again after re-importing a model in Studio. Read-only: the place is
opened, read and closed without saving.
"""

import argparse
import glob
import json
import os
import re
import subprocess
import tempfile
import time
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "roblox", "ServerScriptService", "Modules", "ItemMeshData.lua")
STUDIO = os.environ.get("ROBLOX_STUDIO", "/Applications/RobloxStudio.app/Contents/MacOS/RobloxStudio")
LOG_DIR = os.path.expanduser("~/Library/Logs/Roblox")
PLACE_ID, UNIVERSE_ID = "74883519312765", "9983801557"

LUAU = r"""
print("ITEMS_RUN __TOKEN__")
local HttpService = game:GetService("HttpService")
local SS = game:GetService("ServerStorage")
local root = SS:FindFirstChild("ItemMeshes") or SS
local out = {}
for _, m in ipairs(root:GetChildren()) do
  if not m:IsA("Model") then continue end
  local parts = {}
  for _, d in ipairs(m:GetDescendants()) do
    if d:IsA("MeshPart") then
      table.insert(parts, { n = d.Name, mesh = d.MeshId, tex = d.TextureID, cf = { d.CFrame:GetComponents() },
        s = { d.Size.X, d.Size.Y, d.Size.Z }, col = { d.Color.R, d.Color.G, d.Color.B }, ds = d.DoubleSided })
    end
  end
  out[m.Name] = parts
end
local s = HttpService:JSONEncode(out)
for i = 1, #s, 800 do print("IJ " .. s:sub(i, i + 799)) end
print("ITEMS_END __TOKEN__")
"""


def r(x, n=3):
    v = round(x, n)
    return 0 if v == 0 else v


def lua_part(p, centre):
    cf = p["cf"]
    pos = [cf[0] - centre[0], cf[1] - centre[1], cf[2] - centre[2]]
    rot = cf[3:12]
    ident = all(abs(a - b) < 1e-4 for a, b in zip(rot, [1, 0, 0, 0, 1, 0, 0, 0, 1]))
    fields = ['n = "%s"' % p["n"], 'mesh = "%s"' % p["mesh"], 'tex = "%s"' % p["tex"],
              "s = { %s }" % ", ".join(str(r(x)) for x in p["s"]),
              "p = { %s }" % ", ".join(str(r(x)) for x in pos)]
    if not ident:
        fields.append("rot = { %s }" % ", ".join(str(r(x, 5)) for x in rot))
    return "\t\t{ " + ", ".join(fields) + " },"


def write(data):
    lines = [
        "-- ItemMeshData.lua (generated by tools/studio/item_meshes.py — do not edit)",
        "-- The item models imported in Studio, as data: per item, its MeshParts",
        "-- (mesh / texture ids, size in the import's units, position `p` relative to",
        "-- the model's centre, optional rotation matrix `rot`). ItemModelPreloader",
        "-- builds a model from this when the place has no imported copy.",
        "",
        "return {",
    ]
    for name in sorted(data):
        parts = [p for p in data[name] if p.get("mesh")]
        if not parts:
            continue
        lo = [min(p["cf"][i] - p["s"][i] / 2 for p in parts) for i in range(3)]
        hi = [max(p["cf"][i] + p["s"][i] / 2 for p in parts) for i in range(3)]
        centre = [(a + b) / 2 for a, b in zip(lo, hi)]
        lines.append('\t["%s"] = {' % name)
        for p in sorted(parts, key=lambda q: q["n"]):
            lines.append(lua_part(p, centre))
        lines.append("\t},")
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--place-id", default=PLACE_ID)
    ap.add_argument("--universe-id", default=UNIVERSE_ID)
    ap.add_argument("--timeout", type=int, default=240)
    args = ap.parse_args()
    token = uuid.uuid4().hex
    work = tempfile.mkdtemp(prefix="item-meshes-")
    script = os.path.join(work, "items.luau")
    with open(script, "w") as f:
        f.write(LUAU.replace("__TOKEN__", token))
    t0 = time.time()
    proc = subprocess.Popen([STUDIO, "-task", "RunScript", "-placeId", args.place_id, "-universeId", args.universe_id,
                             "-runScriptFile", script, "-quitAfterExecution"],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    log = None
    while time.time() - t0 < args.timeout:
        time.sleep(3)
        for path in sorted(glob.glob(os.path.join(LOG_DIR, "*_Studio_*_last.log")), key=os.path.getmtime)[-6:]:
            if os.path.getmtime(path) < t0 - 5:
                continue
            with open(path, errors="replace") as f:
                if ("ITEMS_END " + token) in f.read():
                    log = path
        if log:
            break
    time.sleep(2)
    if proc.poll() is None:
        proc.terminate()
    if not log:
        raise SystemExit("no output from Studio (is the place id right, are you logged in?)")
    with open(log, errors="replace") as f:
        txt = f.read()
    data = json.loads("".join(re.findall(r"\[FLog::CreatorOutput\] IJ (.*)", txt)))
    write(data)
    print("%d items, %d parts → %s" % (len(data), sum(len(v) for v in data.values()), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
